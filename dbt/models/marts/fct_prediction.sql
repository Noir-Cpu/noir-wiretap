-- Grain: one ledger prediction. Empty until INFORMANT publishes its first one.
select
    prediction_id as prediction_key,
    ledger_seq,
    prev_hash,
    model_name,
    params_sha,
    data_sha,
    match_id as match_key,
    league_code as league_key,
    match_date as date_key,
    md5(home_team) as home_team_key,
    md5(away_team) as away_team_key,
    home_team,
    away_team,
    kickoff_at,
    published_at,
    date_diff('minute', published_at, kickoff_at) / 60.0 as hours_before_kickoff,
    p_home,
    p_draw,
    p_away,
    book_home,
    book_draw,
    book_away,
    book_home is not null as has_book,
    result,
    is_scored,
    is_first_for_match_model,
    rps,
    log_loss,
    book_rps,
    book_log_loss
from {{ ref('int_informant__scored_predictions') }}
